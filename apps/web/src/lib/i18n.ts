const savedLang = (typeof window !== 'undefined' && localStorage.getItem('timetracker_lang')) || 'ru';

export function applyLanguageDirection(lng: string) {
  if (typeof document !== 'undefined') {
    const isRtl = lng === 'he' || lng === 'ar';
    document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
    document.documentElement.lang = lng;
  }
}

i18n.use(initReactI18next).init({
  resources,
  lng: savedLang,
  fallbackLng: 'en',
  interpolation: {
    escapeValue: false,
  },
});

applyLanguageDirection(savedLang);

export function changeLanguage(lng: string) {
  i18n.changeLanguage(lng);
  localStorage.setItem('timetracker_lang', lng);
  applyLanguageDirection(lng);
}

export default i18n;
